## find even and odd numbers using a for loop.

numbers = [10,15,20,25,30,35]

for i in numbers:
    if i % 2 == 0:
        print(i,"even")
    else:
        print(i,"odd")

## calculate the total using a loop.

numbers = [10,20,40,30,50,80,70,60]
total = 0
for i in numbers:
    total = total + i
print("total:",total)

